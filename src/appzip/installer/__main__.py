import sys
from platform import python_version
import logging
import os
import time
import datetime as dt
from pathlib import Path
from zipfile import ZipFile
from shutil import rmtree
from argparse import ArgumentParser, ArgumentDefaultsHelpFormatter, RawDescriptionHelpFormatter
import venv

from .metadata import Metadata
from .console import Console
from .folder import get_install_dir
from .pretty import prepr
from .utils import *

START_TIME = time.perf_counter_ns()
PYZ_PATH = Path(__file__).parent.parent
ZF = ZipFile(PYZ_PATH)  # Doesn't need to be closed since we aren't writing.
VENV_NAME = ".venv"  # Name of installation venv.
SUBPROCESS_LOG_LEVEL = logging.DEBUG

console = Console(sys.stdout)

HELP = console.theme.style("""
Install the bundled application.

[header]examples:[/]
Install at default location with verbose output:
  [example]%(prog)s[/] [cyan]--log[/] [yellow]DEBUG[/]

Install at custom location:
  [example]%(prog)s [green]path/to/dir/[/]

Install, deleting and reinstalling if already installed:
  [example]%(prog)s [cyan]--reinstall[/]

All options:
  [example]%(prog)s [green]path/to/dir/ -r -l[/] [yellow]INFO[/]\
""")
REPO_LINK = "https://github.com/wolf-william-wetzel/appzip"
EPILOG = console.theme.style(f"""
[header]contents:[/]
{prepr(ZF)}

This installer was generated by appzip: [link]{console.link(REPO_LINK)}\
""")

class ArgparseFormatter(ArgumentDefaultsHelpFormatter, RawDescriptionHelpFormatter): ...

parser = ArgumentParser(description=HELP, epilog=EPILOG, formatter_class=ArgparseFormatter)
parser.add_argument("-r", "--reinstall",
                    action="store_true",
                    help="delete and reinstall if already installed",
                    )
parser.add_argument("path",
                    type=Path,
                    nargs="?",
                    default=get_install_dir(),
                    help="installation directory",
                    )
parser.add_argument("-l", "--log",
                    choices=LOG_LEVELS,
                    type=lambda x: x.upper(),
                    default=LOG_LEVEL,
                    help="output verbosity level",
                    )


def main():
    # Parse arguments.
    args = parser.parse_args()
    args.path = args.path.expanduser().resolve()
    args.log = LOG_LEVELS[args.log]
    show_subprocess_output = args.log <= SUBPROCESS_LOG_LEVEL

    # Set up logging.
    log = logging.getLogger()
    logging.basicConfig(level=args.log, handlers=[console.get_logging_handler()])
    log.debug(console)
    log.debug(args)

    # Load metadata.
    console.status("Loading metadata...")
    md = Metadata.from_json(ZF.read("metadata.json"))
    log.debug(md)

    # Verify proper python version.
    console.status("Checking python version...")
    py_hex_str = f"{md.minimum_python:0>8x}"
    major, minor = int(py_hex_str[:2], 16), int(py_hex_str[2:4], 16)
    if md.minimum_python > sys.hexversion:
        console.exit(f"[error]Installer requires Python >={major}.{minor}, not {python_version()}")
    log.debug(f"Python [string]{python_version()}[/] >= [string]{major}.{minor}[/]")

    # Confirm the installation directory.
    if not console.confirm(
        f"Install {md.app_name} in [path]{args.path}{os.path.sep}[/]?", default=True,
    ):
        if (result := console.ask_folder("Installation directory? ", args.path)) is not None:
            args.path = result
        else:
            console.exit("[error]No directory selected. Installation canceled.")
    install_dir = args.path / md.folder_name

    # Create and verify the installation directory.
    try:
        install_dir.mkdir(parents=True)
        install_dir = install_dir.resolve(strict=True)
    except FileExistsError:
        # The path exists and is a file, not a folder.
        if not install_dir.is_dir():
            console.exit("Installation path is not a directory:", install_dir)
        # The path exists, so this version of the app was installed previously.
        log.warning(f"{md.app_name} is already installed: %s", install_dir)
        if not args.reinstall and not console.confirm("Overwrite previous installation?"):
            console.exit("Exiting installer...", code=0)
        # Overwrite the previous installation.
        log.warning(f"Overwriting previous installation of {md.app_name}")
        errors: list[tuple[str, BaseException]] = []
        rmtree(install_dir, onexc=lambda _, p, e: errors.append((p, e)))
        if errors:
            console.exit("\n".join(f"{p}: {e}" for p, e in errors), exc=False)
        install_dir.mkdir(parents=True)
        install_dir = install_dir.resolve(strict=True)
    except OSError:
        console.exit("Installation path contains symlink loops:", install_dir)
    log.info(f"Installing {md.app_name} to %s", install_dir)

    # Install the app.
    console.status("Extracting...")
    extract_subdir(ZF, "app/", install_dir)

    # Install dependencies.
    if md.dependencies:
        venv_dir = install_dir / "app" / VENV_NAME
        log.debug("Venv: %s", venv_dir)

        # Create venv.
        console.status(f"Creating virtual environment...")
        venv.create(venv_dir, symlinks=not Platform.IS_WIN, with_pip=True, upgrade_deps=True)

        # Install dependencies.
        console.status("" if show_subprocess_output else "Installing dependencies...")
        try:
            venv_install(venv_dir, md.dependencies, show_subprocess_output)
        except FileNotFoundError as exc:
            console.exit(f"[error]{exc}")
    else:
        log.debug("No dependencies to install.")

    # Create entry points.
    console.status("Creating entry points...")
    pass

    # Exit message.
    runtime = dt.timedelta(microseconds=(time.perf_counter_ns() - START_TIME) / 1000)
    log.debug("Finished in %s", runtime)
    console.print(f"[d]Finished in", runtime)
    console.print(f"Installed {md.app_name} to "
                  f"[yellow]{console.link(str(install_dir.parent) + os.path.sep, install_dir.parent)}[/]"
                  f"[l_yellow]{console.link(install_dir.name + os.path.sep, install_dir)}[/]")
